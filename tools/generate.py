#!/usr/bin/env python3
"""Writes the per-language types and producers: one Source, Declaration, Import, Call and Reference child per
language, each under the standard model's parent, each reached from (:CodeProject {key})."""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
# (label prefix, language name as the kind spells it, what to call it in prose)
LANGUAGES = [
    ("TypeScript", "typescript", "TypeScript (and TSX)"), ("JavaScript", "javascript", "JavaScript (and JSX)"),
    ("Python", "python", "Python"), ("Go", "go", "Go"), ("Rust", "rust", "Rust"), ("C", "c", "C"),
    ("Cpp", "cpp", "C++"), ("CSharp", "csharp", "C#"), ("Ruby", "ruby", "Ruby"), ("Php", "php", "PHP"),
    ("Kotlin", "kotlin", "Kotlin"), ("Scala", "scala", "Scala"), ("Swift", "swift", "Swift"),
]

COMMON = {
    "path": '"File path, relative to the project."',
    "language": '"The language, as the producer names it."',
    "line": '{ type: int, description: "Line it is on." }',
    "url": '"The line on the repository\'s host, when it has a file view."',
    "project": '"The project as read: the folder, or host/repo@commit."',
}

KINDS = [
    # suffix, emit, relationship, parent, extra properties, description
    ("Source", "files", "HAS_SOURCE", "Source",
     {"parsed": '{ type: boolean, description: "The file was read and parsed (false: too large, too slow, or unreadable)." }',
      "errors": '{ type: int, description: "Syntax errors its tree holds; the rest of the file still answers." }'},
     "A {prose} source file of a project, with its line count, hash and syntax errors."),
    ("Declaration", "declarations", "DECLARES", "SourceDeclaration", {},
     "A {prose} declaration — type, function, method, field, variable or constant — with its owner, extent, signature, doc comment, annotations and (not for a type) numbered text."),
    ("Import", "imports", "IMPORTS", "SourceImport", {},
     "An import in a {prose} file: what it imports from (`imported`), the names it brings in, and its alias."),
    ("Call", "calls", "CALLS", "CallSite", {},
     "A call in a {prose} file: the called name, what it is called on, its arguments and the function it is in. Matched by NAME only (`resolution: name`): say 'calls something named X', never that it calls a particular X."),
    ("Reference", "references", "REFERENCES", "SourceReference", {},
     "A name a {prose} file uses where a type goes (a parameter's, field's or return type, a base class, a generic argument, an annotation, a constructor), with the declaration it is used in. Matched by NAME only (`resolution: name`): say 'uses a type named X'."),
]

def producer_name(lang, emit):
    return f"{lang}{emit[0].upper()}{emit[1:]}"

for label, lang, prose in LANGUAGES:
    types, producers = [f"# {prose}, read with the `source-tree` kind. Generated by tools/generate.py — edit that, not this.\n"], []
    for suffix, emit, rel, parent, extra, desc in KINDS:
        name = f"{label}{suffix}"
        producer = producer_name(lang, emit)
        producers.append(f"- {{ name: {producer}, kind: source-tree, emit: {emit}, languages: [{lang}] }}")
        props = "\n".join(f"    {k}: {v}" for k, v in {**COMMON, **extra}.items())
        types.append(f"""- name: {name}
  parents: [{parent}]
  visibility: internal
  userAnchor: false
  description: "{desc.format(prose=prose)} Reach it from (:CodeProject {{key}})-[:{rel}]->; name the parent ({parent}) to read every language at once."
  virtualJoins:
    - {{ anchorLabel: CodeProject, relationship: {rel}, keyField: key, recordKeyField: anchorKey, producer: {producer}, maxFanoutTotal: 200000,
        description: "(:CodeProject {{key:$project}})-[:{rel}]->(x:{name})" }}
  properties:
{props}
""")
    (ROOT / "types" / f"{lang}.yml").write_text("\n".join(types))
    (ROOT / "producers" / f"{lang}.yml").write_text(
        f"# {prose}: the `source-tree` kind's five emits, narrowed to {lang}. Generated by tools/generate.py.\n" + "\n".join(producers) + "\n")
print("wrote", len(LANGUAGES), "languages")
